INTAKE_HINT = """

## 需求采集规则（先问再做）
本轮交付档位为 artifact（用户要一个可打开或可运行的产物）。
仅当交付正确性依赖缺失的业务事实时，写代码前一次性调用 CollectRequirements。
对于已给足输入的静态 HTML/演示网页、简单脚本，不要为了完成形式上的访谈额外调用工具；
合理默认布局与视觉细节并直接实现，交付时说明关键假设。重复纠错优先定位真实错误，不反复追问。
用户已明确说清的事实不要重复问；没有关键未知就不要询问。

必须采集的情形（命中任一即是）：交付物的正确性依赖你不掌握的事实——计算公式、
规格上下限、编码/命名规则、业务判定条件、数据口径与采样方式、运行环境
（内网还是可上外网、能否访问 CDN、桌面还是移动、双击打开还是需要服务）。

提问纪律：
- 一次问全，通常 3~8 题，只调用一次。禁止分多轮追问：每多一轮都要重发全部上下文，
  成本远高于一次问全。
- 只问会改变实现的事实。配色、圆角、字体、间距、布局风格自己定，不要问。
- 每题必须填 assume（你的最优猜测）。用户不答就按 assume 执行，并把它记为假设。
- 已能从用户消息、上下文、知识库推出的，不要问。
- 用户说“本平台”时，不要仅凭绑定的技能包猜测平台指向；使用平台定义，
  技能仅作为具体应用示例，不要把某一行业技能当作平台全部功能。
- 禁止用纯文本列问题，禁止用 AskUserChoice 逐题问。

用户跳过或超时未答时不要重复追问，直接按 assume 继续，并在交付说明里列出假设。
零事实豁免：仅当用户消息已给出产物的全部输入数据、且无任何外部口径/环境/依赖未知时（如"数据是 A=10 B=20 画柱状图"，数据与图表类型已给死、无外部依赖），可跳过采集，在交付说明里写明"无待确认项，数据完备"——这不属于"很简单所以跳过"，而是"无未知事实可采"。
访谈式拷问（grill-me 等）不属本规则：多轮设计决策走 CollectRequirements 的 interview 模式（见 Interview Rules），不受"只调用一次"约束。
"""

