# 档位 → 需要追加的提示词段。新增档位或新增规则段只改这张表。
_BY_KIND: dict[str, tuple[str, ...]] = {
    DeliveryKind.ARTIFACT: (INTAKE_HINT, SPEC_LEDGER_HINT, VERIFY_HINT, INCREMENTAL_HINT),
    DeliveryKind.DOCUMENT: (),
    DeliveryKind.ANSWER: (),
}


def hints_for(kind: str) -> str:
    """按档位返回需要拼接的提示词文本（无匹配时返回空串，零增量）。"""
    return "".join(_BY_KIND.get(kind, ()))

INTERVIEW_HINT = """

## Interview Rules（访谈式设计拷问，grill-me 等场景）
激活了 interview 工具组即适用本规则（与交付档位无关，非 artifact 也生效）。
把会话建模成一棵设计树：每个决策分叉出依赖它的子决策。
- frontier：前置决策已敲定、现在就能问（不必猜未听到的答案）的所有决策。每轮用 CollectRequirements（mode="interview"）一次性抛出整条 frontier，通常 3~8 题；每题 assume=你的推荐答案。用户提交后重算 frontier 再抛下一轮，直到 frontier 为空。
- 每题尽量给 choice/multi + allow_other=true（用户可在选项外写自定义）；纯开放决策用 text + multiline=true。不要用散文自问自答、不要用 AskUserChoice 逐题问。
- 事实你自己查：frontier 里需要环境事实（文件/工具/代码/文档）的，自己去查，不要问用户；只把决策抛给用户。正在查的是未敲定前置，只挂住依赖它的题，其余 frontier 照常抛。
- 多轮是本模式的常态，不受 intake 模式"只调用一次"约束；但每轮仍要一次问全整条 frontier，禁止一题一题挤。
- frontier 为空即结束：每个分支都遍历过、没有默默假设。结束前不要动手实现。
"""


def hints_for_interview() -> str:
    """interview 工具组激活时拼接的访谈规则（与交付档位正交）。"""
    return INTERVIEW_HINT


